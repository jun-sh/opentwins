#!/usr/bin/env bash
# P5 offline bundle for both compose projects (core `phm`, `phm-analytics`).
#   offline/bundle.sh lock              online: write images.lock (tag -> registry digest) and
#                                       python/<image>.lock.txt (every PyPI artifact with sha256)
#   offline/bundle.sh build [VERSION]   online for pulls/wheel downloads only; builds the custom images
#                                       with `docker build --network none` from vendored wheels, docker-saves
#                                       everything, generates SBOMs and writes
#                                       dist/opentwins-phm-offline-<VERSION>-<arch>.tar (+ .sha256)
# Never retags or pulls over an image the live stack uses: a local tag that differs from the lock is an error.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd); STACK=$(dirname "$HERE"); REPO=$(dirname "$STACK")
DIST=${DIST:-$HERE/dist}
LOCK=$HERE/images.lock
ARCH=$(docker info --format '{{.Architecture}}')
PY_BASE=docker.io/library/python:3.11-slim-bookworm
# custom image name -> offline tag used by offline/compose/*.offline.yml
declare -A CUSTOM_TAG=(
  [phm-worker]=phm-worker:0.1-offline
  [phm-ditto-ui]=phm-ditto-ui:3.9.9-apk-offline
)
log() { printf '[bundle] %s\n' "$*" >&2; }
die() { printf '[bundle] ERROR: %s\n' "$*" >&2; exit 1; }

# Dummy values only satisfy ${VAR:?} in the compose files so `config --images` can run.
compose_images() {
  local dummy="DITTO_DEVOPS_PASSWORD=x INFLUX_ADMIN_PASSWORD=x INFLUX_TOKEN=x GRAFANA_ADMIN_PASSWORD=x
               DITTO_USER_PASSWORD=x MQTT_EDGE_PASSWORD=x MQTT_TELEGRAF_PASSWORD=x"
  for f in docker-compose.yml phm/docker-compose.yml; do
    (cd "$STACK/$(dirname "$f")" && env -i PATH="$PATH" $dummy \
      docker-compose --env-file /dev/null -f "$(basename "$f")" config --images 2>/dev/null)
  done
  grep -h '^FROM ' "$STACK"/phm/Dockerfile | awk '{print $2}'
  grep -h '^ARG BASE=' "$STACK"/ditto-ui/Dockerfile | cut -d= -f2
}
upstream_refs() { compose_images | grep '^docker\.io/' | sort -u; }

# Registry digest of the local image (what the live stack runs); pulls only when the tag is absent.
local_digest() {
  local ref=$1 repo=${1%:*}; repo=${repo#docker.io/}; repo=${repo#library/}
  docker image inspect "$ref" >/dev/null 2>&1 || docker pull -q "$ref" >/dev/null
  docker image inspect --format '{{range .RepoDigests}}{{println .}}{{end}}' "$ref" \
    | grep -E "^(docker\.io/)?(library/)?${repo}@sha256:" | head -1 | sed 's/.*@//'
}

lock_value() { awk -v r="$1" '$1==r {print $2}' "$LOCK"; }

pyrun() { # pyrun <host dir mounted at /w> <cmd...> : runs in the pinned Python base, host network for proxies
  local dir=$1; shift
  docker run --rm --network host --user "$(id -u):$(id -g)" -e HOME=/tmp -e PIP_DISABLE_PIP_VERSION_CHECK=1 \
    -e HTTP_PROXY -e HTTPS_PROXY -e NO_PROXY -e http_proxy -e https_proxy -e no_proxy \
    -v "$dir:/w" -w /w "$(lock_value "$PY_BASE")" "$@"
}

# Top-level pins per custom Python image (single source of truth stays in the original build files).
py_inputs() {
  case $1 in
    phm-worker) grep -vE '^\s*(#|$)' "$STACK/phm/requirements.txt" ;;
  esac
}

# Writes "name==version --hash=sha256:..." for every artifact in a directory.
hash_lock() {
  python3 -I - "$1" <<'EOF'
import hashlib, pathlib, re, sys
for p in sorted(pathlib.Path(sys.argv[1]).iterdir()):
    if p.suffix == ".whl":
        name, ver = p.name.split("-")[:2]
    elif p.name.endswith(".tar.gz"):
        name, ver = p.name[:-7].rsplit("-", 1)
    else:
        continue
    name = re.sub(r"[-_.]+", "-", name).lower()
    print(f"{name}=={ver} --hash=sha256:{hashlib.sha256(p.read_bytes()).hexdigest()}")
EOF
}

cmd_lock() {
  log "pinning upstream images (local digest first; pulls only missing tags)"
  { echo "# compose/Dockerfile image reference -> registry manifest digest. Generated by offline/bundle.sh lock."
    echo "# Arch of the lock host: $ARCH. Regenerate after any version bump in a compose file or Dockerfile."
    for ref in $(upstream_refs); do
      d=$(local_digest "$ref"); [ -n "$d" ] || die "no registry digest for $ref"
      printf '%-55s %s\n' "$ref" "${ref%:*}@$d"
    done; } > "$LOCK.tmp" && mv "$LOCK.tmp" "$LOCK"
  for img in phm-worker; do
    local w; w=$(mktemp -d "$DIST/lock-XXXX" 2>/dev/null || { mkdir -p "$DIST"; mktemp -d "$DIST/lock-XXXX"; })
    py_inputs "$img" > "$w/in.txt"
    log "resolving Python deps for $img: $(tr '\n' ' ' < "$w/in.txt")"
    pyrun "$w" pip download -q -d dl -r in.txt
    { echo "# $img: every PyPI artifact (wheel or sdist) with sha256. Generated by offline/bundle.sh lock"
      echo "# from $(cd "$REPO" && echo stack/phm/requirements.txt)"
      echo "# on $PY_BASE ($ARCH, cp311). Platform-specific: re-lock on another arch."
      hash_lock "$w/dl"; } > "$HERE/python/$img.lock.txt"
    rm -rf "$w"
  done
  log "wrote $LOCK and python/*.lock.txt"
}

# Ensures <tag> exists locally and is exactly the locked digest; never overwrites a differing local tag.
ensure_image() {
  local ref=$1 pinned; pinned=$(lock_value "$ref"); [ -n "$pinned" ] || die "$ref missing in images.lock"
  docker image inspect "$pinned" >/dev/null 2>&1 || docker pull -q "$pinned" >/dev/null
  local want; want=$(docker image inspect --format '{{.Id}}' "$pinned")
  if docker image inspect "$ref" >/dev/null 2>&1; then
    [ "$(docker image inspect --format '{{.Id}}' "$ref")" = "$want" ] \
      || die "local tag $ref differs from lock $pinned (update the lock or retag deliberately)"
  else
    docker tag "$pinned" "$ref"
  fi
}

vendor_wheels() { # vendor_wheels <image> <ctx dir>: hash-verified download, sdists -> wheels, wheel lock
  local img=$1 ctx=$2 lockf=$HERE/python/$1.lock.txt
  py_inputs "$img" | while read -r pin; do
    grep -qi "^${pin} " "$lockf" || die "$img: input pin '$pin' not in $lockf (run: bundle.sh lock)"
  done
  mkdir -p "$ctx/dl" "$ctx/wheels" "$W/python/sdist"
  cp "$lockf" "$ctx/pypi.lock.txt"
  pyrun "$ctx" pip download -q --no-deps --require-hashes -d dl -r pypi.lock.txt
  local sd; sd=$(cd "$ctx/dl" && ls ./*.tar.gz 2>/dev/null || true)
  # sdist-only packages are built into wheels on the pinned base (build backends come from PyPI here,
  # at bundle time; they are not part of the runtime image). The sdists ship in the bundle for audit.
  [ -z "$sd" ] || pyrun "$ctx" pip wheel -q --no-deps -w wheels $(printf 'dl/%s ' $sd)
  mv "$ctx"/dl/*.whl "$ctx/wheels/"
  [ -z "$sd" ] || mv "$ctx"/dl/*.tar.gz "$W/python/sdist/"
  rmdir "$ctx/dl"
  { echo "# $img: vendored wheels with sha256 (offline install input, pip --require-hashes)"; hash_lock "$ctx/wheels"; } \
    > "$ctx/requirements.lock.txt"
  cp -r "$ctx/wheels" "$W/python/wheels-$img"
  cp "$lockf" "$W/python/$img.pypi.lock.txt"; cp "$ctx/requirements.lock.txt" "$W/python/$img.wheels.lock.txt"
}

build_custom() { # offline builds: no network inside the build
  local c=$W/ctx
  mkdir -p "$c/phm-worker"
  vendor_wheels phm-worker "$c/phm-worker"
  cp "$STACK"/phm/{phm_worker.py,thermal_model.py} "$c/phm-worker/"
  for img in phm-worker; do
    log "docker build --network none ${CUSTOM_TAG[$img]}"
    docker build -q --network none --build-arg "BASE=$PY_BASE" -f "$HERE/docker/$img.Dockerfile" \
      -t "${CUSTOM_TAG[$img]}" "$c/$img" >/dev/null
  done
  # ditto-ui: upstream UI + `apk upgrade` (CVE fix) needs the Alpine mirror, so it is built online from the
  # locked base digest; the bundle ships the resulting image (install.sh --rebuild does not rebuild it).
  local ui_base; ui_base=$(grep -h '^ARG BASE=' "$STACK"/ditto-ui/Dockerfile | cut -d= -f2)
  log "docker build (online, apk) ${CUSTOM_TAG[phm-ditto-ui]}"
  docker build -q --pull=false --build-arg "BASE=$(lock_value "$ui_base")" -t "${CUSTOM_TAG[phm-ditto-ui]}" \
    "$STACK/ditto-ui" >/dev/null
  rm -rf "$c"
}

cmd_build() {
  local ver=${1:-$(date -u +%Y%m%d)-$(git -C "$REPO" rev-parse --short HEAD)}
  local name=opentwins-phm-offline-$ver-$ARCH
  [ -f "$LOCK" ] || die "no images.lock (run: bundle.sh lock)"
  if [ -n "$(git -C "$REPO" status --porcelain -- stack)" ] && [ "${ALLOW_DIRTY:-0}" != 1 ]; then
    die "stack/ has uncommitted changes; the bundle ships the committed tree (ALLOW_DIRTY=1 to override)"
  fi
  W=$DIST/$name; rm -rf "$W"; mkdir -p "$W/images" "$W/python"
  log "bundle $name -> $W"

  git -C "$REPO" archive --format=tar -o "$W/stack.tar" HEAD stack
  cp "$HERE/install.sh" "$W/install.sh"

  local refs; refs=$(upstream_refs)
  for ref in $refs; do ensure_image "$ref"; done
  # check the lock covers exactly the current compose/Dockerfile references
  [ "$(echo "$refs")" = "$(grep -v '^#' "$LOCK" | awk '{print $1}' | sort -u)" ] \
    || die "images.lock does not match the compose files (run: bundle.sh lock)"
  build_custom

  local all; all="$refs $(printf '%s ' "${CUSTOM_TAG[@]}")"
  : > "$W/images/images.ids"
  for ref in $all; do
    printf '%s %s %s\n' "$ref" "$(docker image inspect --format '{{.Id}}' "$ref")" \
      "$(lock_value "$ref" || true)" >> "$W/images/images.ids"
  done
  log "docker save ($(wc -l < "$W/images/images.ids") images)"
  docker save $all | gzip -1 > "$W/images/images.tar.gz"

  "$HERE/sbom.sh" "$W/sbom" $all
  python3 -I "$HERE/licence_summary.py" "$W/sbom" "$HERE/components.json" > "$W/sbom/licence-summary.md"
  mkdir -p "$HERE/sbom"
  cp "$W/sbom/licence-summary.md" "$W/sbom/licence-flags.csv" "$W/sbom/vuln-summary.md" "$HERE/sbom/"
  (cd "$W/sbom" && tar -czf "$HERE/sbom/cyclonedx.tar.gz" images python)

  { printf '{"name":"%s","version":"%s","arch":"%s","created":"%s","git_commit":"%s",\n' \
      "$name" "$ver" "$ARCH" "$(date -u +%FT%TZ)" "$(git -C "$REPO" rev-parse HEAD)"
    printf ' "images":[%s]}\n' "$(awk '{printf "%s{\"ref\":\"%s\",\"id\":\"%s\",\"pinned\":\"%s\"}", (NR>1 ? "," : ""), $1, $2, $3}' "$W/images/images.ids")"; } \
    > "$W/bundle.json"
  (cd "$W" && find . -type f ! -name SHA256SUMS -print0 | sort -z | xargs -0 sha256sum > SHA256SUMS)
  tar -C "$DIST" -cf "$DIST/$name.tar" "$name"
  (cd "$DIST" && sha256sum "$name.tar" > "$name.tar.sha256")
  log "done: $DIST/$name.tar ($(du -h "$DIST/$name.tar" | cut -f1)); checksum $DIST/$name.tar.sha256"
}

case ${1:-} in
  lock) cmd_lock ;;
  build) shift; cmd_build "$@" ;;
  *) sed -n '2,9p' "$0"; exit 2 ;;
esac
