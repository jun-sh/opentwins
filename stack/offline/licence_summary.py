#!/usr/bin/env python3
"""Licence summary from CycloneDX SBOMs (Syft output) plus a curated list of top-level components.

usage: licence_summary.py <sbom dir> <components.json>  > licence-summary.md
Reads <sbom dir>/images/*.cdx.json and python/*.cdx.json, writes <sbom dir>/licence-flags.csv
(every component that is not plainly permissive) and prints a Markdown summary.

Classification is a keyword heuristic over SPDX ids / free-text names; it is an audit aid that points
reviewers at packages, not a legal opinion. An "A OR B" expression takes the least restrictive option,
"A AND B" (and several licence entries on one package) the most restrictive one.
"""
import csv
import json
import pathlib
import re
import sys
from collections import Counter, defaultdict

CATS = ["permissive", "weak-copyleft", "strong-copyleft", "unknown", "network-copyleft", "non-osi/special"]
FLAG = {"network-copyleft", "non-osi/special", "unknown"}
RULES = [  # first match wins; order matters (AGPL before GPL, LGPL before GPL)
    ("non-osi/special", r"SSPL|SERVER SIDE PUBLIC|BUSL|BUSINESS SOURCE|ELASTIC|COMMONS.CLAUSE|NASA|NOSA|"
                        r"PROPRIETARY|COMMERCIAL|\bNC\b|NON.?COMMERCIAL|JSON\b|\bSUN\b"),
    ("network-copyleft", r"AGPL|AFFERO|\bOSL\b|OSL-|\bRPL"),
    ("weak-copyleft", r"LGPL|LESSER|LIBRARY GENERAL|MPL|MOZILLA|\bEPL|ECLIPSE PUBLIC|CDDL|\bCPL\b|"
                      r"GPL.*WITH .*EXCEPTION|CLASSPATH|LLGPL"),
    ("strong-copyleft", r"GPL|EUPL|CC-BY-SA|GFDL|SLEEPYCAT|QPL"),
    ("permissive", r"MIT|BSD|APACHE|ISC|ZLIB|PSF|PYTHON|0BSD|UNLICENSE|CC0|PUBLIC.DOMAIN|X11|EXPAT|UNICODE|"
                   r"BSL-1\.0|BOOST|FSFAP|FSFUL|HPND|CURL|OPENSSL|SSLEAY|BZIP2|LIBPNG|IJG|PERMISSIVE|"
                   r"ARTISTIC|PERL|RUBY|TCL|NTP|W3C|WTFPL|BEERWARE|EDL|INFO-ZIP|SMLNJ|MIT-CMU|POSTGRESQL|"
                   r"OFL|FTL|LATEX2E|TEXT-TABS|KAZLIB|BSLA|GAP|TINYSCHEME|CC-BY-[0-9]|SPENCER|MS-PL"),
]


def classify_one(lic: str) -> str:
    u = lic.upper()
    for cat, rx in RULES:
        if re.search(rx, u):
            return cat
    return "unknown"


def classify_expr(expr: str) -> str:
    alts = re.split(r"\s+OR\s+", expr.strip("() "))
    best = None
    for alt in alts:
        parts = [p.strip("() ") for p in re.split(r"\s+AND\s+", alt) if p.strip("() ")]
        worst = max((CATS.index(classify_one(p)) for p in parts), default=CATS.index("unknown"))
        best = worst if best is None else min(best, worst)
    return CATS[best]


def licences(comp: dict) -> list:
    out = []
    for entry in comp.get("licenses", []) or []:
        lic = entry.get("expression") or entry.get("license", {}).get("id") or entry.get("license", {}).get("name")
        if lic and not lic.startswith("sha256:"):  # Syft names unrecognised licence texts by their hash
            out.append(lic)
    return out


def classify(comp: dict):
    lics = licences(comp)
    if not lics:
        return "unknown", ""
    return CATS[max(CATS.index(classify_expr(l)) for l in lics)], " ; ".join(sorted(set(lics)))


def main(sbom_dir: str, components_file: str) -> None:
    root = pathlib.Path(sbom_dir)
    rows, per_image = [], defaultdict(Counter)
    for f in sorted(root.glob("images/*.cdx.json")) + sorted(root.glob("python/*.cdx.json")):
        doc = json.loads(f.read_text())
        meta = doc.get("metadata", {}).get("component", {})
        image = f"{meta.get('name', f.stem)}:{meta.get('version', '?')}".replace("docker.io/", "")
        scope = "python" if f.parent.name == "python" else "image"
        seen = set()
        for c in doc.get("components", []):
            if c.get("type") in ("file", "operating-system"):
                continue
            key = (c.get("name"), c.get("version"))
            if key in seen:
                continue
            seen.add(key)
            cat, lic = classify(c)
            ptype = (c.get("purl", "pkg:?/").split(":", 1)[1].split("/", 1)[0]) if c.get("purl") else "?"
            if scope == "image":
                per_image[image][cat] += 1
            rows.append(dict(scope=scope, image=image, name=c.get("name"), version=c.get("version", ""),
                             type=ptype, licences=lic, category=cat))

    with open(root / "licence-flags.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["scope", "image", "type", "name", "version", "licences", "category"])
        w.writeheader()
        w.writerows(r for r in rows if r["category"] != "permissive")

    comps = json.loads(pathlib.Path(components_file).read_text())
    p = print
    p("# Licence summary\n")
    p("Generated by `offline/licence_summary.py` from the Syft CycloneDX SBOMs of the offline bundle. Heuristic")
    p("classification for audit triage, not a legal opinion. Non-permissive rows: `licence-flags.csv`.\n")
    p("## Top-level components (curated, from upstream licence files)\n")
    p("| Component | Image / package | Licence | Class | OSI approved | Flag / note |")
    p("|---|---|---|---|---|---|")
    for c in comps["components"]:
        p(f"| {c['name']} | `{c['where']}` | {c['licence']} | {c['class']} | {c['osi']} | {c.get('note', '')} |")
    p("\n## Packages per image by licence class (SBOM, all package types)\n")
    p("| Image | " + " | ".join(CATS) + " |")
    p("|---|" + "---:|" * len(CATS))
    for image, cnt in sorted(per_image.items()):
        p(f"| `{image}` | " + " | ".join(str(cnt.get(c, 0)) for c in CATS) + " |")
    p("\n`unknown` is mostly Go modules and Java jars whose licence Syft cannot read from the binary/jar")
    p("metadata (Grafana, InfluxDB, Telegraf, Ditto); the curated table above covers the products themselves.\n")
    p("## Flagged: network copyleft and non-OSI / special licences (all images)\n")
    flagged = sorted({(r["name"], r["version"], r["licences"], r["category"]) for r in rows
                      if r["category"] in ("network-copyleft", "non-osi/special")})
    p("| Package | Version | Licence | Class | Images |")
    p("|---|---|---|---|---|")
    for name, ver, lic, cat in flagged:
        imgs = sorted({r["image"] for r in rows if (r["name"], r["version"]) == (name, ver)})
        p(f"| {name} | {ver} | {lic} | {cat} | {', '.join(f'`{i}`' for i in imgs)} |")
    p("\n## Python packages (custom images) that are not permissive\n")
    p("| Image | Package | Version | Licence | Class |")
    p("|---|---|---|---|---|")
    for r in sorted((r for r in rows if r["scope"] == "python" and r["category"] != "permissive"),
                    key=lambda r: (r["image"], r["name"])):
        p(f"| `{r['image']}` | {r['name']} | {r['version']} | {r['licences'] or '(none declared)'} | {r['category']} |")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
